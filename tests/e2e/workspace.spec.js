import { test, expect } from '@playwright/test';
import { PNG } from '../helpers.js';

test('登录 → 上传 → 原图 → 收藏 → 相册 → 删除 → 密钥创建与撤销 → 注销', async ({ page, request }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '欢迎来到 pppic' })).toBeVisible();
  await page.getByLabel('管理口令', { exact: true }).fill(process.env.PPPIC_E2E_TOKEN);
  await page.getByRole('button', { name: '进入工作空间' }).click();
  await expect(page.locator('#page-title')).toHaveText('我的图库.');
  const filename = `${testInfo.project.name}-测试图片.png`;
  // 保持每个项目文件内容唯一，同时保留 PNG 数据，浏览器允许 IEND 后附加数据。
  const content = Buffer.concat([PNG, Buffer.from(testInfo.project.name)]);
  await page.locator('#file-input').setInputFiles({ name: filename, mimeType: 'image/png', buffer: content });
  await expect(page.locator('.queue-item')).toContainText('已完成');
  const card = page.locator('.image-card').filter({ hasText: filename });
  await expect(card).toBeVisible();
  const imageURL = await card.locator('img').getAttribute('src');
  expect((await request.get(imageURL)).status()).toBe(200);
  await expect(card.locator('img')).toHaveJSProperty('complete', true);
  expect(await card.locator('img').evaluate(image => image.naturalWidth)).toBeGreaterThan(0);
  await card.getByRole('button', { name: `收藏 ${filename}`, exact: true }).click();
  await expect(card.getByRole('button', { name: `取消收藏 ${filename}`, exact: true })).toBeVisible();
  await card.getByRole('button', { name: `查看 ${filename}`, exact: true }).click();
  await page.getByLabel('所属相册').fill('浏览器验收');
  await page.getByRole('button', { name: '保存修改' }).click();
  await expect(page.getByRole('status')).toContainText('图片信息已更新');
  await page.getByRole('button', { name: '关闭图片详情' }).click();
  await page.getByRole('searchbox').fill(filename);
  await expect(page.locator('.image-card')).toHaveCount(1);
  await page.getByRole('searchbox').fill('不存在的图片');
  await expect(page.getByRole('heading', { name: '这里暂时没有图片' })).toBeVisible();
  await page.getByRole('button', { name: '重置', exact: true }).click();
  await expect(card).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await card.getByRole('button', { name: `删除 ${filename}`, exact: true }).click();
  await expect(card).toHaveCount(0);
  expect((await request.get(imageURL)).status()).toBe(404);
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: '打开导航' }).click();
  await page.getByRole('button', { name: 'API 密钥', exact: true }).click();
  await page.getByLabel('密钥名称').fill('浏览器验收密钥');
  await page.getByRole('button', { name: '创建密钥', exact: true }).click();
  await expect(page.locator('#new-secret')).toHaveText(/^pppic_/);
  const token = await page.locator('#new-secret').textContent();
  await page.getByRole('button', { name: '关闭密钥窗口' }).click();
  await expect(page.locator('#new-secret')).toHaveText('');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  const revoked = await request.get('/api/v1/images', { headers: { authorization: 'Bearer ' + token } });
  expect(revoked.status()).toBe(401);
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: '打开导航' }).click();
  await page.getByRole('button', { name: /管理员.*退出登录/ }).click();
  await expect(page.getByRole('heading', { name: '欢迎来到 pppic' })).toBeVisible();
  expect(errors).toEqual([]);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  expect(overflow).toBe(false);
});
